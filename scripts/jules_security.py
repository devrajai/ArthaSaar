#!/usr/bin/env python3
"""Start a Jules SECURITY session - but only when there is actually an alert to fix.

Why gated: GitHub's own scanners (secret scanning, Dependabot, CodeQL) are deterministic and
free on a public repo. Jules is an LLM - unreliable as a scanner, good at reasoning about a
specific flagged issue. So GitHub finds, Jules fixes. A security task that runs every day
whether or not anything is open is just a daily PR to review.

Same key, same mechanism as jules_trigger.py. JULES_API_KEY must be a repository secret;
it is never read from a file and never printed.
"""
import json, os, sys, urllib.request, urllib.error

API = "https://jules.googleapis.com/v1alpha"
GH = "https://api.github.com"
OWNER = os.environ.get("REPO_OWNER", "devrajai")
REPO = os.environ.get("REPO_NAME", "ArthaSaar")
BRANCH = os.environ.get("BASE_BRANCH", "main")
KEY = os.environ.get("JULES_API_KEY", "").strip()
GH_TOKEN = os.environ.get("GITHUB_TOKEN", "").strip()
DRY = "--dry" in sys.argv


def gh(path):
    """Read the repo's own alerts with the workflow token. [] on any problem."""
    if not GH_TOKEN:
        return None
    req = urllib.request.Request(GH + path)
    req.add_header("Authorization", "Bearer " + GH_TOKEN)
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("User-Agent", "ArthaSaar-security-check")
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read().decode("utf-8", "replace"))
    except urllib.error.HTTPError as e:
        # 404 = the feature is not enabled on this repo. That is not a failure.
        print("  %s -> HTTP %s" % (path.split("?")[0], e.code))
        return None
    except Exception as e:
        print("  %s -> %s" % (path.split("?")[0], type(e).__name__))
        return None


def open_alerts():
    """(count, summary). Count of open alerts across all three scanners."""
    found = []
    for label, path in [
        ("secret scanning", "/repos/%s/%s/secret-scanning/alerts?state=open&per_page=50" % (OWNER, REPO)),
        ("Dependabot",      "/repos/%s/%s/dependabot/alerts?state=open&per_page=50" % (OWNER, REPO)),
        ("code scanning",   "/repos/%s/%s/code-scanning/alerts?state=open&per_page=50" % (OWNER, REPO)),
    ]:
        data = gh(path)
        if isinstance(data, list) and data:
            found.append("%d %s" % (len(data), label))
        elif isinstance(data, list):
            print("  %s: none open" % label)
    return found


PROMPT = """Security pass on this repository.

Open alerts right now: {alerts}

GitHub's own scanners found these. Your job is to FIX them, not to re-scan.

For each open alert:
1. Fix the ROOT CAUSE, not the symptom.
2. For a vulnerable dependency, bump it to a patched version and confirm the existing tests
   still pass (scripts/test_mf.py, test_indicators.py, test_backtest.py, test_timesfm.py).
3. For a code-scanning finding, fix the code. If it is a genuine false positive, say WHY in
   the PR and leave it alone rather than making a change that does nothing.
4. For an exposed secret, do NOT try to rewrite git history or force-push - that does not
   unpublish anything on a public repo. Report it and say the credential must be rotated.

Hard constraints:
- NEVER commit a credential. If a fix needs one, use a GitHub Secret and
  ${{ secrets.NAME }}. Never a literal.
- Do not add a paid dependency.
- Do not rewrite git history or force-push.
- Do not touch docs/index.html. It is 29 sections in a single file and other work edits it.
- Do not change docs/*.json - those are generated by the pipeline.

Open ONE pull request. Report the alert count before and after, and list anything you chose
not to fix and why.

Do the work now and open the PR. Do not stop to ask for plan approval, and do not reply with
a plan alone."""


def main():
    alerts = open_alerts()
    if alerts:
        summary = "; ".join(alerts)
        print("gate: RUN (%s)" % summary)
    else:
        print("gate: SKIP (no open security alerts)")
        print("nothing to fix - not starting a session")
        return 0

    if not KEY:
        print("JULES_API_KEY is not set - skipping.")
        print("Add it in Settings > Secrets and variables > Actions, then re-run.")
        return 0

    payload = {
        "prompt": PROMPT.format(alerts=summary),
        "title": "Security fix: %s" % summary[:60],
        "sourceContext": {
            "source": "sources/github/%s/%s" % (OWNER, REPO),
            "githubRepoContext": {"startingBranch": BRANCH},
        },
        "automationMode": "AUTO_CREATE_PR",
        "requirePlanApproval": False,
    }
    if DRY:
        print("[dry run] would POST /sessions with title:", payload["title"])
        return 0

    req = urllib.request.Request(API + "/sessions", data=json.dumps(payload).encode(), method="POST")
    req.add_header("X-Goog-Api-Key", KEY)
    req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            out = json.loads(r.read().decode("utf-8", "replace"))
    except urllib.error.HTTPError as e:
        print("Jules API HTTP %s: %s" % (e.code, e.read().decode("utf-8", "replace")[:300]))
        return 0
    except Exception as e:
        print("Jules API error: %s" % type(e).__name__)
        return 0

    print("session started:", out.get("id"))
    print("  view:", out.get("url"))
    return 0


if __name__ == "__main__":
    _rc = main()
    import os as _os, sys as _sys
    _sys.stdout.flush(); _sys.stderr.flush()
    _os._exit(_rc)
